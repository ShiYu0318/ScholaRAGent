def nest(lang_index):
    root = {}
    for key, pair in S.items():
        node = root
        *parents, leaf = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
            if not isinstance(node, dict):
                raise SystemExit(f"鍵衝突：{key}")
        if leaf in node:
            raise SystemExit(f"鍵衝突：{key}")
        node[leaf] = pair[lang_index]
    return root


def main():
    out = Path(__file__).resolve().parent.parent / "src" / "i18n"
    for name, index in (("zh", 0), ("en", 1)):
        body = json.dumps({"translation": nest(index)}, ensure_ascii=False, indent=2)
        (out / f"{name}.ts").write_text(
            "// 由 tools/strings.py 產生，請勿手動修改。\n"
            f"export default {body};\n", encoding="utf-8")
    print(f"{len(S)} keys")


if __name__ == "__main__":
    main()
